import { diffSnapshots, section } from './schema.ts'
import { deriveRepairs, droppedObjects, repairSql, q, literal } from './repairs.ts'
import type { ColumnRow, DefRow, Diff, Snapshot } from './types.ts'

const ID_TO_TIMESTAMP = 'unfork_id_to_timestamp'
const OLD_TYPE_SUFFIX = '_unfork_old'

const ID_TO_TIMESTAMP_FUNCTION = `
-- Misskey "aid" ids start with 8 base36 characters of milliseconds since
-- 2000-01-01, which is enough to recover a row's creation time. Other id
-- schemes decode to nonsense outside any plausible range, hence the fallback.
CREATE OR REPLACE FUNCTION ${ID_TO_TIMESTAMP}(id text)
RETURNS timestamptz AS $$
DECLARE
  acc bigint := 0;
  pos int;
  ts  timestamptz;
BEGIN
  IF id IS NULL OR length(id) < 8 THEN RETURN now(); END IF;
  FOR i IN 1..8 LOOP
    pos := strpos('0123456789abcdefghijklmnopqrstuvwxyz', lower(substr(id, i, 1)));
    IF pos = 0 THEN RETURN now(); END IF;
    acc := acc * 36 + (pos - 1);
  END LOOP;
  ts := timestamptz '2000-01-01 00:00:00+00' + (acc || ' milliseconds')::interval;
  IF ts < timestamptz '2014-01-01 00:00:00+00' OR ts > now() THEN RETURN now(); END IF;
  RETURN ts;
EXCEPTION WHEN others THEN
  RETURN now();
END;
$$ LANGUAGE plpgsql IMMUTABLE;
`.trim()

export interface Revert {
  sql: string
  warnings: string[]
  diff: Diff
}

function fillValueFor(column: ColumnRow, source: Snapshot, target: Snapshot): string | null {
  const type = column.type
  if (/^timestamp/.test(type)) {
    const id = source.schema.columns.find(c => c.table === column.table && c.name === 'id')
    return id && /^(text|character varying)/.test(id.type) ? `${ID_TO_TIMESTAMP}("id")` : 'now()'
  }
  if (type === 'boolean') return 'false'
  if (/^(smallint|integer|bigint|numeric|real|double precision)/.test(type)) return '0'
  if (/^(text|character varying)/.test(type)) return '\'\''
  if (type.endsWith('[]')) return '\'{}\''
  if (type === 'jsonb' || type === 'json') return '\'{}\''
  const enumType = target.schema.enums.find(e => e.name === type)
  return enumType ? literal(enumType.labels[0]) : null
}

const identityClause = (c: ColumnRow): string => ` GENERATED ${c.identity === 'a' ? 'ALWAYS' : 'BY DEFAULT'} AS IDENTITY`
const withIfNotExists = (def: string): string => def.replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS ')
const isForeignKey = (c: DefRow): boolean => c.def.startsWith('FOREIGN KEY')
const addConstraint = (c: DefRow): string => `ALTER TABLE ${q(c.table)} DROP CONSTRAINT IF EXISTS ${q(c.name)}, ADD CONSTRAINT ${q(c.name)} ${c.def};`

export function generateRevert(source: Snapshot, target: Snapshot, { pre = '', post = '', regenerate = '' } = {}): Revert {
  const diff = diffSnapshots(source.schema, target.schema)
  const S = <K extends Parameters<typeof section>[1]>(name: K) => section(diff, name)
  const dropped = droppedObjects(diff)
  const { repairs, warnings } = deriveRepairs(source, target)
  const labels = { source: source.ref.label, target: target.ref.label }

  const constraintBacked = new Set([...source.schema.constraints, ...target.schema.constraints].map(c => `${c.table}.${c.name}`))
  const plainIndex = (i: DefRow): boolean => !constraintBacked.has(`${i.table}.${i.name}`)

  const out: string[] = []
  const say = (...lines: string[]): void => {
    out.push(...lines)
  }
  const stage = (n: number, title: string): void => say('', `-- ${'-'.repeat(73)}`, `-- ${n}. ${title}`, `-- ${'-'.repeat(73)}`, '')
  let usesIdDecoder = false

  const backfill = (column: ColumnRow): void => {
    const value = fillValueFor(column, source, target)
    if (!value) {
      warnings.push(`${column.table}.${column.name} is NOT NULL with no default and no value could be derived; fill it in pre.sql or apply will fail`)
      return
    }
    if (value.startsWith(ID_TO_TIMESTAMP)) usesIdDecoder = true
    say(`UPDATE ${q(column.table)} SET ${q(column.name)} = ${value} WHERE ${q(column.name)} IS NULL;`)
  }

  say(
    `-- misskey-unfork: ${labels.source} -> ${labels.target}`,
    '--',
    '-- Generated by comparing the schema each revision\'s migrations produce on',
    '-- an empty database. Do not edit; regenerate with:',
    `--   ${regenerate}`,
    '--',
    '-- Runs as one transaction with the instance stopped, which is what',
    '-- `unfork apply` does after a backup has been taken.',
  )

  stage(1, 'data repair before the schema changes')
  const helperSlot = out.length
  for (const r of repairs.filter(r => r.phase === 'pre')) say(`-- ${r.reason}`, repairSql(r), '')
  if (pre.trim()) say('-- pre.sql', pre.trim(), '')

  stage(2, `create what ${labels.target} has and ${labels.source} lacks`)
  for (const e of S('extensions').onlyB) say(`CREATE EXTENSION IF NOT EXISTS ${q(e.name)};`)
  for (const s of S('sequences').onlyB) say(`CREATE SEQUENCE IF NOT EXISTS ${q(s.name)};`)
  for (const e of S('enums').onlyB) say(`CREATE TYPE ${q(e.name)} AS ENUM (${e.labels.map(literal).join(', ')});`)

  const newTables = new Set(S('tables').onlyB.map(t => t.name))
  for (const table of S('tables').onlyB) {
    const columns = target.schema.columns.filter(c => c.table === table.name).map((c) => {
      let def = `${q(c.name)} ${c.type}`
      if (c.identity) def += identityClause(c)
      else if (c.default) def += ` DEFAULT ${c.default}`
      if (!c.nullable) def += ' NOT NULL'
      return def
    })
    say(`CREATE TABLE IF NOT EXISTS ${q(table.name)} (`, columns.map((c, i) => `  ${c}${i < columns.length - 1 ? ',' : ''}`).join('\n'), ');')
    if (table.comment) say(`COMMENT ON TABLE ${q(table.name)} IS ${literal(table.comment)};`)
    for (const c of target.schema.columns.filter(c => c.table === table.name && c.comment)) {
      say(`COMMENT ON COLUMN ${q(c.table)}.${q(c.name)} IS ${literal(c.comment)};`)
    }
    say('')
  }

  for (const c of S('columns').onlyB.filter(c => !newTables.has(c.table))) {
    const t = q(c.table)
    const n = q(c.name)
    if (c.identity) {
      say(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${n} ${c.type}${identityClause(c)};`)
    }
    else if (!c.nullable && !c.default) {
      say(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${n} ${c.type};`)
      backfill(c)
      say(`ALTER TABLE ${t} ALTER COLUMN ${n} SET NOT NULL;`)
    }
    else {
      say(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${n} ${c.type}${c.default ? ` DEFAULT ${c.default}` : ''}${c.nullable ? '' : ' NOT NULL'};`)
    }
    if (c.comment) say(`COMMENT ON COLUMN ${t}.${n} IS ${literal(c.comment)};`)
    say('')
  }

  // Not CONCURRENTLY: that cannot run inside the transaction, and the instance is offline anyway.
  for (const i of S('indexes').onlyB.filter(plainIndex)) say(`${withIfNotExists(i.def)};`)
  const newConstraints = S('constraints').onlyB
  // Dropped first: a long-lived instance can already hold a constraint its
  // fork's fresh migrations no longer create.
  for (const c of newConstraints.filter(c => !isForeignKey(c))) say(addConstraint(c))
  for (const c of newConstraints.filter(isForeignKey)) say(addConstraint(c))

  stage(3, `drop what ${labels.source} added`)
  for (const c of [...S('constraints').onlyA, ...S('constraints').changed.map(x => x.a)]) {
    say(`ALTER TABLE ${q(c.table)} DROP CONSTRAINT IF EXISTS ${q(c.name)};`)
  }
  // Dropping a constraint removes the index behind it; DROP INDEX on that index errors.
  for (const i of [...S('indexes').onlyA, ...S('indexes').changed.map(x => x.a)].filter(plainIndex)) {
    say(`DROP INDEX IF EXISTS ${q(i.name)};`)
  }
  say('')

  const byTable = new Map<string, string[]>()
  for (const c of dropped.columns) byTable.set(c.table, [...(byTable.get(c.table) ?? []), c.name])
  for (const [table, columns] of [...byTable].sort()) {
    say(`ALTER TABLE ${q(table)}`, columns.map((n, i) => `  DROP COLUMN IF EXISTS ${q(n)}${i < columns.length - 1 ? ',' : ';'}`).join('\n'))
  }
  for (const t of [...dropped.tables].sort()) say(`DROP TABLE IF EXISTS ${q(t)} CASCADE;`)
  for (const s of S('sequences').onlyA) say(`DROP SEQUENCE IF EXISTS ${q(s.name)};`)
  for (const e of S('enums').onlyA) say(`DROP TYPE IF EXISTS ${q(e.name)};`)
  say('')

  const redefined = S('indexes').changed.map(x => x.b).filter(plainIndex)
  if (redefined.length || S('constraints').changed.length) {
    say(`-- definitions that differ, recreated as ${labels.target} has them`)
    for (const i of redefined) say(`${withIfNotExists(i.def)};`)
    for (const { b } of S('constraints').changed) say(addConstraint(b))
    say('')
  }

  if (S('enums').changed.length) {
    // Postgres cannot remove an enum label in place, so the type is rebuilt and its columns re-cast.
    stage(4, 'rebuild enum types whose labels differ')
    for (const change of S('enums').changed) {
      const name = change.key
      const old = q(`${name}${OLD_TYPE_SUFFIX}`)
      say(`-- ${name}: ${JSON.stringify(change.a.labels)} -> ${JSON.stringify(change.b.labels)}`)
      say(`ALTER TYPE ${q(name)} RENAME TO ${old};`)
      say(`CREATE TYPE ${q(name)} AS ENUM (${change.b.labels.map(literal).join(', ')});`)
      for (const col of target.schema.columns.filter(c => c.type === name || c.type === `${name}[]`)) {
        const t = q(col.table)
        const n = q(col.name)
        const array = col.type.endsWith('[]') ? '[]' : ''
        say(`ALTER TABLE ${t} ALTER COLUMN ${n} DROP DEFAULT;`)
        say(`ALTER TABLE ${t} ALTER COLUMN ${n} TYPE ${q(name)}${array} USING ${n}::text${array}::${q(name)}${array};`)
        if (col.default) say(`ALTER TABLE ${t} ALTER COLUMN ${n} SET DEFAULT ${col.default};`)
      }
      say(`DROP TYPE ${old};`, '')
    }
  }

  const changedColumns = S('columns').changed.filter(({ b }) => !newTables.has(b.table))
  const changedTables = S('tables').changed
  if (changedColumns.length || changedTables.length) {
    stage(5, 'column definitions that differ')
    for (const { a, b } of changedColumns) {
      const t = q(b.table)
      const n = q(b.name)
      if (a.type !== b.type) say(`ALTER TABLE ${t} ALTER COLUMN ${n} TYPE ${b.type} USING ${n}::${b.type};`)
      if (a.identity !== b.identity) {
        warnings.push(`${b.table}.${b.name}: identity differs (${JSON.stringify(a.identity)} -> ${JSON.stringify(b.identity)}) and is left as is`)
      }
      if (a.default !== b.default) {
        say(b.default
          ? `ALTER TABLE ${t} ALTER COLUMN ${n} SET DEFAULT ${b.default};`
          : `ALTER TABLE ${t} ALTER COLUMN ${n} DROP DEFAULT;`)
      }
      if (a.nullable && !b.nullable) {
        if (b.default) say(`UPDATE ${t} SET ${n} = ${b.default} WHERE ${n} IS NULL;`)
        else backfill(b)
        say(`ALTER TABLE ${t} ALTER COLUMN ${n} SET NOT NULL;`)
      }
      else if (!a.nullable && b.nullable) {
        say(`ALTER TABLE ${t} ALTER COLUMN ${n} DROP NOT NULL;`)
      }
      if (a.comment !== b.comment) say(`COMMENT ON COLUMN ${t}.${n} IS ${b.comment ? literal(b.comment) : 'NULL'};`)
    }
    for (const { b } of changedTables) say(`COMMENT ON TABLE ${q(b.name)} IS ${b.comment ? literal(b.comment) : 'NULL'};`)
    say('')
  }

  stage(6, `set the migrations table to the ${target.migrations.length} rows ${labels.target} expects`)
  say('DELETE FROM "migrations";')
  say('INSERT INTO "migrations" ("timestamp", "name") VALUES')
  say(target.migrations.map((m, i) => `  (${m.timestamp}, ${literal(m.name)})${i < target.migrations.length - 1 ? ',' : ';'}`).join('\n'))
  say('DO $$ BEGIN PERFORM setval(pg_get_serial_sequence(\'migrations\', \'id\'), (SELECT COALESCE(MAX("id"), 1) FROM "migrations")); END $$;')

  stage(7, 'data repair after the schema changes')
  for (const r of repairs.filter(r => r.phase === 'post')) say(`-- ${r.reason}`, repairSql(r), '')
  if (post.trim()) say('-- post.sql', post.trim(), '')
  if (usesIdDecoder) {
    say(`DROP FUNCTION IF EXISTS ${ID_TO_TIMESTAMP}(text);`)
    out.splice(helperSlot, 0, ID_TO_TIMESTAMP_FUNCTION, '')
  }

  return { sql: out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n', warnings, diff }
}
